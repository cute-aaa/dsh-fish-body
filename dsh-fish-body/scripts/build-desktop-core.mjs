#!/usr/bin/env node
/**
 * 把共享层与 layered 装配各构建成一份经典 script，供桌面 Helper 从 file:// 直接加载：
 *   runtime/electron-helper/shared-core.js   源 src/shared/index.ts          → 全局 window.PetShared
 *   runtime/electron-helper/layered-core.js  源 src/client/pet/render/layered → 全局 window.PetLayered
 * 必须是经典 script（iife）而非 ESM：Helper 页面走 file://，Chromium 对它的 ES module 有 CORS 限制。
 * 两份产物都先于 renderer.js 加载，页面直接读全局，不另建模块系统。
 * 只产构建产物，不做类型检查、不写声明；由发布链的 npm run build:desktop-core 调用。
 * @module dsh-fish-body/scripts/build-desktop-core
 */
import { rolldown } from 'rolldown';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const HELPER = join(ROOT, 'runtime', 'electron-helper');

/** 一份经典 script 产物的定义：入口、产物、全局名、文件头里的源路径。 */
const TARGETS = [
  {
    input: join(ROOT, 'src', 'shared', 'index.ts'),
    out: join(HELPER, 'shared-core.js'),
    name: 'PetShared',
    source: 'src/shared/index.ts',
  },
  {
    input: join(ROOT, 'src', 'client', 'pet', 'render', 'layered', 'index.ts'),
    out: join(HELPER, 'layered-core.js'),
    name: 'PetLayered',
    source: 'src/client/pet/render/layered/index.ts',
  },
];

/**
 * 构建一份产物。
 *
 * @param target - 入口、产物路径、全局名与源路径。
 * @throws 构建或写盘失败时向上抛，由调用方统一报错退出。
 */
async function buildOne(target) {
  const bundle = await rolldown({ input: target.input, platform: 'browser' });
  await bundle.write({ format: 'iife', name: target.name, file: target.out });
  // 产物落进仓库且由 Helper 从 file:// 加载：文件头必须声明生成来源，避免被手改后又被构建无声覆盖。
  const banner = [
    '/**',
    ' * @generated by `npm run build:desktop-core`（scripts/build-desktop-core.mjs），请勿手改。',
    ` * 源文件：${target.source}。`,
    ' */',
  ].join('\n');
  const code = readFileSync(target.out, 'utf8');
  if (!code.startsWith('/**')) writeFileSync(target.out, banner + '\n' + code);
}

try {
  for (const target of TARGETS) await buildOne(target);
  console.log('[build-desktop-core] ✓ runtime/electron-helper/shared-core.js (window.PetShared)');
  console.log('[build-desktop-core] ✓ runtime/electron-helper/layered-core.js (window.PetLayered)');
} catch (error) {
  console.error('[build-desktop-core] build failed:', error);
  process.exit(1);
}
